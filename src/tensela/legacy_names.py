def level_name(text: str, levels) -> str:
    """A level written by hand, to the name the data gives it: as it is if it exists; if not, the one it is
    called in the language of the interface («fila» → «row»), or its name of before. A list «a, b», each one."""
    from .language import tr
    parts = [x.strip() for x in text.split(",")]
    output = []
    for part in parts:
        if part not in levels:
            for level in levels:
                if str(tr(level)).lower() == part.lower() or OLD_LEVELS.get(part) == level:
                    part = level
                    break
        output.append(part)
    return ", ".join(output) if len(parts) > 1 else output[0]
