def input_in_english(node: str, name: str, value, options: tuple = ()):
    """An input given with its old Spanish name and value (an old project, an old test) → its English name and
    value. `node` is the English node name; `options`, the English options of that input."""
    english = INPUTS.get(node, {}).get(name, name)
    if isinstance(value, str) and options and value not in options:
        value = OPTIONS.get(node, {}).get(english, {}).get(value, value)
    return english, value


#: English input name → its old Spanish name (one to one).
OLD_INPUTS = {at: es for inputs in INPUTS.values() for es, at in inputs.items()}


def old_input(name: str) -> str:
    """The old Spanish name of an input."""
    return OLD_INPUTS.get(name, name)


def _new_inputs() -> dict:
    from collections import Counter
    votes: dict[str, Counter] = {}
    for inputs in INPUTS.values():
        for es, at in inputs.items():
            votes.setdefault(es, Counter())[at] += 1
    return {es: c.most_common(1)[0][0] for es, c in votes.items()}


NEW_INPUTS = _new_inputs()


def input_name(name: str) -> str:
    """An input name as it is now: an English one, as it is; an old Spanish one (without knowing the node), its
    usual English name."""
    return name if name in OLD_INPUTS else NEW_INPUTS.get(name, name)


